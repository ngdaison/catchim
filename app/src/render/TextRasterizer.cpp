std::vector<uint8_t> TextRasterizer::rasterize(
    const TextProperties& props,
    int32_t& outWidth,
    int32_t& outHeight
) {
    int scale = std::max(1, props.fontSize / 8);
    int charWidth = 8 * scale;
    int charHeight = 8 * scale;

    int textLen = static_cast<int>(props.text.length());
    int contentWidth = textLen * charWidth;
    int contentHeight = charHeight;

    outWidth = contentWidth + props.padding * 2;
    outHeight = contentHeight + props.padding * 2;

    std::vector<uint8_t> buffer(outWidth * outHeight * 4, 0);

    // 1. Fill background if non-transparent
    if (props.bgA > 0) {
        for (int y = 0; y < outHeight; ++y) {
            for (int x = 0; x < outWidth; ++x) {
                int idx = (y * outWidth + x) * 4;
                buffer[idx + 0] = props.bgR;
                buffer[idx + 1] = props.bgG;
                buffer[idx + 2] = props.bgB;
                buffer[idx + 3] = props.bgA;
            }
        }
    }

    // 2. Render each glyph
    int startX = props.padding;
    int startY = props.padding;

    for (int i = 0; i < textLen; ++i) {
        char ch = props.text[i];
        int glyphIndex = static_cast<int>(ch) - 32;
        if (glyphIndex < 0 || glyphIndex >= 95) {
            glyphIndex = 0; // Space
        }

        const uint8_t* glyph = s_font8x8_basic[glyphIndex];

        int charOriginX = startX + i * charWidth;

        for (int row = 0; row < 8; ++row) {
            uint8_t rowBits = glyph[row];
            for (int col = 0; col < 8; ++col) {
                if (rowBits & (1 << col)) {
                    // Draw scaled block
                    for (int sy = 0; sy < scale; ++sy) {
                        for (int sx = 0; sx < scale; ++sx) {
                            int px = charOriginX + col * scale + sx;
                            int py = startY + row * scale + sy;
                            if (px >= 0 && px < outWidth && py >= 0 && py < outHeight) {
                                int idx = (py * outWidth + px) * 4;
                                buffer[idx + 0] = props.textR;
                                buffer[idx + 1] = props.textG;
                                buffer[idx + 2] = props.textB;
                                buffer[idx + 3] = props.textA;
                            }
                        }
                    }
                }
            }
        }
    }

    return buffer;
}

